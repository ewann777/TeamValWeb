test('IndexedDB: creación simultánea entre pestañas conserva un solo equipo por jugador', async ({ page, context }) => {
  await page.goto('/app/scrims/equipos')
  await expect(page.getByText('2 equipos', { exact: true })).toBeVisible()
  const second = await context.newPage()
  await second.goto('/app/scrims/equipos')
  await expect(second.getByText('2 equipos', { exact: true })).toBeVisible()
  const create = (p: Page, name: string) => p.evaluate(async (name) => {
    const path = '/src/data/local/teams.ts', models = '/src/domain/models/teams.ts'
    const { LocalTeamsRepository } = await import(path), { emptyTeam } = await import(models)
    const repo = new LocalTeamsRepository()
    return repo.execute('demo-me', ['demo-me'], { type: 'saveTeam', draft: { ...emptyTeam, name, tag: name.slice(-3), description: 'Prueba de escritura concurrente.' } })
  }, name)
  const results = await Promise.all([create(page, 'Equipo AAA'), create(second, 'Equipo BBB')])
  expect(results.filter((r: { ok: boolean }) => r.ok)).toHaveLength(1)
  await page.reload()
  await expect(page.getByText('3 equipos', { exact: true })).toBeVisible()
})

test('IndexedDB: datos dañados muestran error, reintento y reinicio explícito', async ({ page }) => {
  await page.goto('/app/scrims')
  await expect(page.locator('.scrim-post')).toHaveCount(2)
  await page.evaluate(async () => {
    await new Promise<void>((resolve, reject) => {
      const req = indexedDB.open('teamval.teams.demo.v1', 1)
      req.onerror = () => reject(req.error)
      req.onsuccess = () => { const db = req.result; const tx = db.transaction('snapshots', 'readwrite'); tx.objectStore('snapshots').put({ version: 99 }, 'current'); tx.oncomplete = () => { db.close(); resolve() } }
    })
  })
  await page.reload()
  await expect(page.getByText('No pudimos cargar esta sección')).toBeVisible()
  await page.getByRole('button', { name: 'Reintentar' }).click()
  await expect(page.getByText('No pudimos cargar esta sección')).toBeVisible()
  page.once('dialog', (d) => d.accept())
  await page.getByRole('button', { name: 'Reiniciar demo W4' }).click()
  await expect(page.locator('.scrim-post')).toHaveCount(2)
})

