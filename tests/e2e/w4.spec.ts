test('reinicio W4 conserva datos de W3', async ({ page }) => {
  await createTeam(page)
  await page.evaluate(() => {
    // Guardar un snapshot W3 real para comprobar que W4 no lo toca.
    const key = 'teamval.community.demo.v1'
    localStorage.setItem('w3-preservation-check', localStorage.getItem(key) ?? 'absent')
  })
  page.once('dialog', (d) => d.accept())
  await page.getByRole('button', { name: 'Reiniciar demo W4' }).click()
  await expect(page.getByText('Demo W4 reiniciada.')).toBeVisible()
  await expect(page.getByText('Este equipo no existe')).toBeVisible()
  expect(await page.evaluate(() => (localStorage.getItem('teamval.community.demo.v1') ?? 'absent') === localStorage.getItem('w3-preservation-check'))).toBe(true)
  await page.getByRole('link', { name: 'Ver equipos', exact: true }).click()
  await expect(page.getByText('2 equipos', { exact: true })).toBeVisible()
})

